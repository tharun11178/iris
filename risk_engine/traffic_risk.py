"""
IRIS Traffic Risk Calculator (Phase 4)
Calculates distance-decayed spatial traffic risk generated by dynamic road users
(vehicles, autos, motorcycles, pedestrians, cattle, trucks, pushcarts).
Accumulates multiple nearby risks probabilistically: R_total = 1 - prod(1 - r_i).
"""

import math
import numpy as np
from typing import List, Dict, Any
from world.world_model import WorldModel
from risk_engine.config import OBJECT_RISK_WEIGHTS, TRAFFIC_INFLUENCE_RADIUS


class TrafficRiskModel:
    """
    Computes current dynamic traffic spatial risk.
    """

    def __init__(self, weights: Dict[str, float] = OBJECT_RISK_WEIGHTS, radius: float = TRAFFIC_INFLUENCE_RADIUS):
        self.weights = weights
        self.radius = radius

    def compute(self, world_model: WorldModel, traffic_matrix: np.ndarray):
        """
        Populates traffic_matrix in-place with current dynamic traffic risk values.
        """
        traffic_matrix.fill(0.0)
        grid = world_model.grid
        converter = world_model.converter
        res = grid.grid_res

        rad_cells = int(math.ceil(self.radius / res))

        # We compute 1 - risk product for smooth probabilistic risk accumulation
        one_minus_risk = np.ones((grid.num_rows, grid.num_cols), dtype=np.float64)

        for actor in world_model.dynamic_actors:
            a_type = actor["type"]
            a_x, a_y = actor["x"], actor["y"]
            confidence = actor.get("confidence", 1.0)
            weight = self.weights.get(a_type, 0.75) * confidence

            r_center, c_center = converter.world_to_grid(a_x, a_y)

            r_min = max(0, r_center - rad_cells)
            r_max = min(grid.num_rows - 1, r_center + rad_cells)
            c_min = max(0, c_center - rad_cells)
            c_max = min(grid.num_cols - 1, c_center + rad_cells)

            for r in range(r_min, r_max + 1):
                for c in range(c_min, c_max + 1):
                    cell = grid.cells[r][c]
                    dist = math.hypot(cell.x_world - a_x, cell.y_world - a_y)
                    if dist <= self.radius:
                        spatial_decay = max(0.0, 1.0 - (dist / self.radius))
                        individual_risk = weight * spatial_decay
                        one_minus_risk[r, c] *= (1.0 - individual_risk)

        traffic_matrix[:] = np.clip(1.0 - one_minus_risk, 0.0, 1.0)
