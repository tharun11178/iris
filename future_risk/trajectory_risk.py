"""
IRIS Trajectory Risk Calculator (Phase 10).
Calculates trajectory-driven spatial risk for predicted object motion across future time steps t,
incorporating object size, object class risk weights, prediction confidence decay, and multi-hypothesis branching.
"""

import math
import numpy as np
from typing import List, Dict, Tuple, Optional, Any

from tracking.track import Track
from prediction.trajectory import PredictionSet, PredictedTrajectory, PredictionHypothesis
from world.world_model import WorldModel
from future_risk.config import (
    OBJECT_RISK_WEIGHTS,
    OBJECT_INFLUENCE_RADII,
    HYPOTHESIS_AGGREGATION_METHOD,
)


class TrajectoryRiskModel:
    """
    Computes time-discretized spatial risk generated by dynamic actor motion predictions.
    """

    def __init__(self, aggregation_method: str = HYPOTHESIS_AGGREGATION_METHOD):
        self.aggregation_method = aggregation_method

    def get_object_risk_weight(self, object_type: Any) -> float:
        """Returns prototype baseline risk weight [0.0, 1.0] for object class."""
        type_str = object_type.name if hasattr(object_type, "name") else str(object_type)
        return OBJECT_RISK_WEIGHTS.get(type_str, 0.75)

    def get_object_influence_radius(self, object_type: Any, track: Optional[Track] = None) -> float:
        """Returns baseline spatial influence radius (in meters) for object class."""
        type_str = object_type.name if hasattr(object_type, "name") else str(object_type)
        base_r = OBJECT_INFLUENCE_RADII.get(type_str, 2.0)
        if track is not None:
            # Scale slightly with physical object dimensions
            dim_factor = max(track.length, track.width) / 2.0
            return max(base_r, dim_factor)
        return base_r

    def compute_timestep_trajectory_risk(
        self,
        tracks: List[Track],
        prediction_set: Optional[PredictionSet],
        time_offset: float,
        world_model: WorldModel,
        out_matrix: np.ndarray,
    ):
        """
        Calculates spatial risk generated by all predicted trajectories at a specific future time offset t.
        
        :param tracks: Active persistent Track objects.
        :param prediction_set: Phase 8 PredictionSet.
        :param time_offset: Relative time offset in seconds (e.g. 0.0s, 0.2s, 1.0s ... 3.0s).
        :param world_model: WorldModel instance.
        :param out_matrix: 2D numpy array (num_rows, num_cols) to populate with trajectory risk.
        """
        grid = world_model.grid
        converter = world_model.converter
        grid_res = converter.grid_res
        num_rows = grid.num_rows
        num_cols = grid.num_cols

        if not tracks:
            return

        # Map track_id -> List of candidate (trajectory, weight) tuples for this timestamp
        track_candidates: Dict[str, List[Tuple[Tuple[float, float], float, Track, float]]] = {}

        for track in tracks:
            track_candidates[track.track_id] = []
            obj_weight = self.get_object_risk_weight(track.object_type)

            # Check if prediction_set contains trajectories or hypotheses for this track
            t_list: List[PredictedTrajectory] = []
            hypo_list: List[PredictionHypothesis] = []

            if prediction_set is not None:
                t_list = [tr for tr in prediction_set.trajectories if tr.track_id == track.track_id]
                hypo_list = [h for h in prediction_set.hypotheses if h.track_id == track.track_id]

            if hypo_list:
                # Multi-hypothesis branch processing
                for h in hypo_list:
                    traj = h.trajectory
                    if traj and traj.predicted_positions:
                        pos = self._interpolate_position(traj, time_offset, track.current_position)
                        conf = traj.confidence * getattr(h, "confidence", 1.0)
                        track_candidates[track.track_id].append((pos, obj_weight, track, conf))

            elif t_list and t_list[0].predicted_positions:
                # Nominal single trajectory
                traj = t_list[0]
                pos = self._interpolate_position(traj, time_offset, track.current_position)
                conf = traj.confidence
                track_candidates[track.track_id].append((pos, obj_weight, track, conf))

            else:
                # Fallback: Project constant velocity position x_t = x_0 + v_x * t, y_t = y_0 + v_y * t
                pos_x = track.current_position[0] + track.velocity[0] * time_offset
                pos_y = track.current_position[1] + track.velocity[1] * time_offset
                conf = track.confidence
                track_candidates[track.track_id].append(((pos_x, pos_y), obj_weight, track, conf))

        # Rasterize candidates onto grid for this timestep
        for track_id, candidates in track_candidates.items():
            if not candidates:
                continue

            # Per-track temporary risk matrix for conservative MAX hypothesis aggregation
            track_matrix = np.zeros((num_rows, num_cols), dtype=np.float64)

            for (px, py), obj_w, track, conf in candidates:
                radius = self.get_object_influence_radius(track.object_type, track)
                r_center, c_center = converter.world_to_grid(px, py)
                radius_cells = max(1, int(radius / grid_res))

                r_min = max(0, r_center - radius_cells)
                r_max = min(num_rows, r_center + radius_cells + 1)
                c_min = max(0, c_center - radius_cells)
                c_max = min(num_cols, c_center + radius_cells + 1)

                for r in range(r_min, r_max):
                    for c in range(c_min, c_max):
                        cell_x, cell_y = converter.grid_to_world(r, c)
                        dist = math.hypot(cell_x - px, cell_y - py)
                        if dist <= radius:
                            # Spatial Gaussian decay kernel
                            gaussian_decay = math.exp(-0.5 * (dist / max(0.1, radius / 2.0)) ** 2)
                            cell_risk = obj_w * conf * gaussian_decay

                            if self.aggregation_method == "MAX":
                                track_matrix[r, c] = max(track_matrix[r, c], cell_risk)
                            else:
                                track_matrix[r, c] = min(1.0, track_matrix[r, c] + cell_risk)

            # Combine track matrix into output matrix conservatively (MAX)
            np.maximum(out_matrix, track_matrix, out=out_matrix)

    def _interpolate_position(
        self,
        traj: PredictedTrajectory,
        t_offset: float,
        fallback_pos: Tuple[float, float],
    ) -> Tuple[float, float]:
        """Interpolates predicted position (x, y) at continuous time offset t from trajectory timesteps."""
        if not traj.predicted_positions or not traj.timestamps:
            return fallback_pos

        t_start = traj.timestamps[0]
        target_t = t_start + t_offset

        # Exact match or bound checks
        if target_t <= traj.timestamps[0]:
            return traj.predicted_positions[0]
        if target_t >= traj.timestamps[-1]:
            return traj.predicted_positions[-1]

        # Find interval
        for i in range(len(traj.timestamps) - 1):
            t1, t2 = traj.timestamps[i], traj.timestamps[i + 1]
            if t1 <= target_t <= t2:
                alpha = (target_t - t1) / (t2 - t1 + 1e-6)
                p1 = traj.predicted_positions[i]
                p2 = traj.predicted_positions[i + 1]
                ix = p1[0] + alpha * (p2[0] - p1[0])
                iy = p1[1] + alpha * (p2[1] - p1[1])
                return (ix, iy)

        return traj.predicted_positions[-1]
